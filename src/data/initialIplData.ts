const batForm = (scores: number[]): RecentMatchForm[] =>
  scores.map((s, i) => ({
    match: `M${i + 1}`,
    runs: s,
    score: s,
    label: `${s} runs`,
  }));

const bowlForm = (wkts: number[]): RecentMatchForm[] =>
  wkts.map((w, i) => ({
    match: `M${i + 1}`,
    wickets: w,
    score: w * 25 + 15,
    label: `${w} wkts`,
  }));

const arForm = (runs: number[], wkts: number[]): RecentMatchForm[] =>
  runs.map((r, i) => ({
    match: `M${i + 1}`,
    runs: r,
    wickets: wkts[i] ?? 0,
    score: r + (wkts[i] ?? 0) * 24,
    label: `${r}r · ${wkts[i] ?? 0}w`,
  }));

